-- EN 16931 phase 1: read-only reference code lists.
--
-- Pinned source: Peppol BIS Billing 3.0.21 (May 2026 release), code list publication 2026-03-06, https://docs.peppol.eu/poacc/billing/3.0/codelist/
-- Lists and the version string published on each page:
--   ISO3166: identifier ISO3166, version 2013, 251 codes
--   ISO4217: identifier ISO4217, version 2018-01-01, 178 codes
--   UNECERec20: identifier UNECERec20, version Revision 11e, 2162 codes
--   UNCL5305: identifier UNCL5305, version D.16B, 10 codes
--   UNCL4461: identifier UNCL4461, version D.16B, 84 codes
--   vatex: identifier vatex, version no version string on the page, 88 codes
--   eas: identifier eas, version no version string on the page, 83 codes
--   ref_countries also includes EL, Greece's VAT prefix, which is not an ISO 3166 postal country.
--   ref_currencies.minor_units: ISO 4217 Maintenance Agency list one published 2026-09-17.
--   CNH is on the Peppol currency list and is not in that ISO list. It uses 2 minor units, the same as CNY.
-- VAT category flags follow CEN-EN16931-UBL.sch published with this release:
--   exemption required: E (BR-E-10), AE (BR-AE-10), K (BR-IC-10), G (BR-G-10), O (BR-O-10)
--   rate must be zero: Z (BR-Z-05), E (BR-E-05), AE (BR-AE-05), K (BR-IC-05), G (BR-G-05)
--   O omits the VAT rate in UBL (BR-O-05); the flag stores that as zero
--   S requires a rate above zero (BR-S-05) and forbids an exemption (BR-S-10)
--   L and M allow a rate of zero or more (BR-AF-05, BR-AG-05) and forbid an exemption (BR-AF-10, BR-AG-10)
--   B is the Italian split-payment category in the Peppol UNCL5305 subset (BR-CL-17, BR-B-01)
-- Irish VAT electronic address scheme: EAS 9935 Ireland VAT number.
-- UNCL4461 code 51: the published title element stops mid-parenthesis and the page continues it in the description. The seed stores the joined title.

create table public.ref_countries (
  code text primary key,
  name text not null,
  active boolean not null default true,
  vat_prefix_only boolean not null default false,
  constraint ref_countries_code_check check (code ~ '^[A-Z0-9]{2}$'),
  constraint ref_countries_name_check check (char_length(name) between 1 and 200)
);

comment on table public.ref_countries is 'Peppol BIS Billing 3.0.21 (May 2026 release), code list publication 2026-03-06, https://docs.peppol.eu/poacc/billing/3.0/codelist/ ISO 3166-1 alpha-2, page version 2013, plus EL as a VAT prefix only.';
comment on column public.ref_countries.code is 'ISO 3166-1 alpha-2 postal country, EN 16931 BT-40 and BT-55. EL is Greece''s VAT prefix and is not a postal country.';
comment on column public.ref_countries.name is 'Country name from the Peppol ISO 3166-1 list.';
comment on column public.ref_countries.active is 'True for every code in the pinned Peppol list.';
comment on column public.ref_countries.vat_prefix_only is 'True only for EL. A postal address cannot use a VAT-prefix-only code.';

